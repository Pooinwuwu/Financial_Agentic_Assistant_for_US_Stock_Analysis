from typing import Any, Optional
from pydantic import BaseModel, Field

class Message(BaseModel):
    role: str = Field(..., description="Role of the author: system, user, assistant, or tool")
    content: str = Field(..., description="Message text content")
    name: Optional[str] = Field(None, description="Optional name of the tool if role is tool")
    tool_calls: Optional[list[dict[str, Any]]] = Field(None, description="Optional tool calls generated by assistant")

class ChatRequest(BaseModel):
    query: str = Field(..., description="Natural language query from user")
    conversation_history: list[Message] = Field(default_factory=list, description="Prior conversation context")

class Citation(BaseModel):
    source: str = Field(..., description="Document source identifier, e.g. NVDA_2023_10K_Item1A")
    snippet: str = Field(..., description="Excerpt or summary of the cited text")
    score: Optional[float] = Field(None, description="Relevance score or similarity metric")

class ToolExecutionLog(BaseModel):
    tool: str = Field(..., description="Name of the executed tool")
    args: dict[str, Any] = Field(..., description="Arguments passed to the tool")
    output: Any = Field(..., description="Raw execution output from the tool")
    error: Optional[str] = Field(None, description="Error message if execution failed")

class ChatResponse(BaseModel):
    answer: str = Field(..., description="Final synthesized answer from the agent")
    steps: list[ToolExecutionLog] = Field(default_factory=list, description="Audit trace of tools called")
    citations: list[Citation] = Field(default_factory=list, description="Source citations referenced in the answer")
    total_steps: int = Field(0, description="Number of agent iterations executed")

class EvaluationCase(BaseModel):
    id: str = Field(..., description="Unique test case identifier")
    question: str = Field(..., description="The user query to be evaluated")
    category: str = Field(..., description="Evaluation category: sql, rag, python, multi_hop, or safety")
    expected_tool: Optional[str] = Field(None, description="Expected primary tool invocation")
    ground_truth: Any = Field(..., description="Expected quantitative value or factual proposition")
    metadata: dict[str, Any] = Field(default_factory=dict, description="Metadata such as tickers, fiscal years")
